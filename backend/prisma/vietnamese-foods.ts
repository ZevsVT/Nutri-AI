import { createHash } from "node:crypto";

export interface FoodSeed {
  id: string;
  canonicalName: string;
  nameVi: string;
  nameEn: string;
  category: string;
  cuisine: "Vietnamese";
  foodType: string;
  aliases: string[];
  subcategory: string;
  region: string;
  cookingMethod: string;
  servingUnit: string;
  defaultServingSize: number;
}

function stableId(slug: string): string {
  const hex = createHash("sha256")
    .update(`nutri-ai-food:${slug}`)
    .digest("hex")
    .slice(0, 32);
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-4${hex.slice(13, 16)}-8${hex.slice(17, 20)}-${hex.slice(20)}`;
}

function food(
  slug: string,
  nameVi: string,
  nameEn: string,
  category: string,
  foodType: string,
  cookingMethod: string,
  region = "NATIONWIDE",
  servingUnit = "SERVING",
  defaultServingSize = 1,
  aliases: string[] = [],
): FoodSeed {
  return {
    id: stableId(slug),
    canonicalName: slug,
    nameVi,
    nameEn,
    category,
    cuisine: "Vietnamese",
    foodType,
    aliases: [
      ...new Set([nameVi, slug.replace(/-/g, " "), nameEn, ...aliases]),
    ],
    subcategory: category,
    region,
    cookingMethod,
    servingUnit,
    defaultServingSize,
  };
}

