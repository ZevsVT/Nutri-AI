export function validateFoodDefinitions(
  definitions = vietnameseFoodDefinitions,
): void {
  const seen = new Map<string, string>();
  const slugs = new Set<string>();
  for (const item of definitions) {
    if (
      !item.id ||
      !item.canonicalName ||
      !item.nameVi ||
      !item.nameEn ||
      !item.category ||
      !item.foodType
    ) {
      throw new Error(
        `Food ${item.canonicalName || "<unknown>"} is missing required fields`,
      );
    }
    if (slugs.has(item.canonicalName))
      throw new Error(`Duplicate food slug: ${item.canonicalName}`);
    slugs.add(item.canonicalName);
    for (const alias of item.aliases) {
      const normalized = alias
        .normalize("NFD")
        .replace(/\p{Diacritic}/gu, "")
        .toLocaleLowerCase("vi")
        .trim()
        .replace(/\s+/g, " ");
      const owner = seen.get(`${normalized}:vi`);
      if (owner && owner !== item.canonicalName)
        throw new Error(
          `Alias collision: ${alias} (${owner}, ${item.canonicalName})`,
        );
      seen.set(`${normalized}:vi`, item.canonicalName);
    }
  }
}

validateFoodDefinitions();
